#!/bin/sh
# Generate the single-header build of SS_Lib from include/ and src/.
#
#   ./create_single_header.sh [output]     (default: include/ss_lib_single.h)
#
# The output is deterministic, so CI can diff it against the committed copy
# (make check-single-header). Never edit include/ss_lib_single.h by hand.

set -e

ROOT="$(cd "$(dirname "$0")" && pwd)"
OUTPUT="${1:-$ROOT/include/ss_lib_single.h}"
CONFIG="$ROOT/include/ss_config.h"
HEADER="$ROOT/include/ss_lib.h"
SOURCE="$ROOT/src/ss_lib.c"

for f in "$CONFIG" "$HEADER" "$SOURCE"; do
    [ -f "$f" ] || { echo "Error: missing $f" >&2; exit 1; }
done

VERSION=$("$ROOT/scripts/version.sh")
TMP="$OUTPUT.tmp"

# Contents of a header between its include guard lines
unguard() {
    sed -n "/^#ifndef $2/,/^#endif.*$2/{
/^#ifndef $2/d
/^#define $2\$/d
/^#endif.*$2/d
p
}" "$1"
}

{
    cat <<EOF
/*
 * SS_Lib $VERSION - single-header build (generated, do not edit)
 *
 * Generated by create_single_header.sh from include/ss_config.h,
 * include/ss_lib.h and src/ss_lib.c.
 *
 * In exactly one C file:
 *   #define SS_IMPLEMENTATION
 *   #include "ss_lib_single.h"
 * Everywhere else, include it without SS_IMPLEMENTATION. Define any
 * configuration macros (see the configuration section) before including,
 * identically in every file.
 */

EOF
    # Feature-test macros must precede every system header
    echo "#ifdef SS_IMPLEMENTATION"
    sed -n '/SS_FEATURE_MACROS_BEGIN/,/SS_FEATURE_MACROS_END/p' "$SOURCE"
    echo "#endif"
    echo ""
    echo "#ifndef SS_LIB_SINGLE_H"
    echo "#define SS_LIB_SINGLE_H"
    echo "#define SS_CONFIG_H"
    echo "#define SS_LIB_H"
    echo ""
    echo "/* ===== Configuration ===== */"
    unguard "$CONFIG" SS_CONFIG_H
    echo ""
    echo "/* ===== API ===== */"
    unguard "$HEADER" SS_LIB_H | grep -v '#include "ss_config.h"'
    echo ""
    echo "#endif /* SS_LIB_SINGLE_H */"
    echo ""
    echo "/* ===== Implementation ===== */"
    echo "#if defined(SS_IMPLEMENTATION) && !defined(SS_LIB_SINGLE_IMPLEMENTED)"
    echo "#define SS_LIB_SINGLE_IMPLEMENTED"
    sed -e '1,/SS_FEATURE_MACROS_END/d' -e '/#include "ss_lib.h"/d' "$SOURCE"
    echo "#endif /* SS_IMPLEMENTATION */"
} | sed -e '/^$/N;/^\n$/D' > "$TMP"

mv "$TMP" "$OUTPUT"
echo "Generated $OUTPUT (SS_Lib $VERSION)"
